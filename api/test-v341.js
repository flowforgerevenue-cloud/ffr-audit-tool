'use strict';
const assert=require('node:assert/strict');
const {quantify}=require('../engine/quantificationEngine');
const {normalize}=require('../engine/financialEngine');
const {buildSimulation,baselineGrowth}=require('../engine/simulationEngine');
const {check}=require('../engine/integrityEngine');
const {runRules}=require('../rules/registry');
(async()=>{
  const observed={url:'https://sample.test/contact',name:'Contact Form Friction',observation:'Six fields on the contact page',state:'observed'};
  const base={stage:'Series B',currency:'USD',traffic:1000,acv:40000,closeRate:20,leak:{severity:.5,evidence:[observed]}};
  const opportunity=quantify(base);assert.equal(opportunity.available,true);
  assert.equal(opportunity.annualUnadjusted,opportunity.lostDeals*40000*12);
  assert.equal(quantify({...base,leak:{severity:.5,evidence:[{...observed,state:'unverified'}]}}).available,false);
  assert.equal(quantify({...base,acv:null}).available,false);
  assert.equal(quantify({...base,trafficType:'all'}).available,false);
  assert.equal(quantify({...base,currency:null}).available,false);
  const financial=normalize({text:'Year,Revenue\n2023,800000\n2024,1000000\n2025,1250000',declaredRevenue:1250000,currency:'USD'});
  assert.deepEqual(financial.historicalRevenue.map(x=>x.value),[800000,1000000,1250000]);
  assert.equal(financial.dataQuality,'medium');
  assert.equal(baselineGrowth(financial).rate,.25);
  const clash=normalize({text:'2024 Revenue 1000000\n2025 Revenue 1250000',declaredRevenue:2000000,currency:'USD'});
  assert.equal(clash.historyGrowthConflict,true);
  assert.equal(baselineGrowth(clash).rate,0);
  const currencies=normalize({text:'2024 Revenue NGN 500000\n2025 Revenue NGN 750000',declaredRevenue:750000,currency:'USD'});
  assert.equal(currencies.historicalRevenue.length,0);
  const notStatement=normalize({text:'FlowForge Revenue Opportunity Report\nPublic Funnel Diagnostic\n2023 Revenue 800000\n2024 Revenue 1000000',declaredRevenue:2000000,currency:'USD'});
  assert.equal(notStatement.historicalRevenue.length,0);
  const noHistory=normalize({text:'Some non-financial company narrative',declaredRevenue:1000000,currency:'USD'});
  assert.equal(baselineGrowth(noHistory).rate,0);
  const high=buildSimulation({currentRevenue:10000,opportunity,financial:noHistory,revenueBasis:'annualized-run-rate'});
  assert.equal(high.projectionStatus,'withheld-plausibility');
  assert.equal(high.summary.base_5yr,high.summary.status_quo_5yr);
  assert.equal(high.scenariosDistinct,false);
  const integrity=check({currency:'USD',opportunity,simulation:high,financial:noHistory});assert.equal(integrity.ok,true);
  const reasonable=buildSimulation({currentRevenue:100000000,opportunity,financial:noHistory,revenueBasis:'annualized-run-rate'});
  assert.equal(reasonable.projectionStatus,'conditional-sensitivity');
  assert(reasonable.summary.base_5yr>reasonable.summary.status_quo_5yr);
  const basisHeld=buildSimulation({currentRevenue:100000000,opportunity,financial:noHistory,revenueBasis:'recognized'});assert.equal(basisHeld.projectionStatus,'withheld-basis');assert.equal(basisHeld.summary.base_5yr,basisHeld.summary.status_quo_5yr);
  const empty=buildSimulation({currentRevenue:100000,opportunity:{available:false},financial:noHistory});
  assert.equal(empty.baselineGrowth,0);assert(empty.years.every(y=>y.status_quo===y.aggressive));
  const url='https://example.test/contact';
  const page={type:'contact',url,text:'Contact our sales team for business infrastructure solutions.',ctas:['Contact sales'],forms:['a','b','c','d','e','f'],title:'Talk to sales'};
  const obs=runRules(page);assert(obs.some(x=>x.state==='observed'&&x.name==='Contact Form Friction'));
  assert(obs.filter(x=>x.state==='unverified').every(x=>!x.observation.includes('loss')));
  // Vercel forecast contract and returned currency/flat-hold behavior.
  const api=require('./simulate');const res={statusCode:0,setHeader(){},status(c){this.statusCode=c;return this},json(data){this.value=data;return data}};
  await api({method:'POST',headers:{host:'localhost'},body:{company:'SYNTHETIC FINTECH ONLY',currency:'USD',stage:'Series B',currentRevenue:1250000,fileContent:Buffer.from('Year,Revenue\n2023,800000\n2024,1000000\n2025,1250000').toString('base64'),fileType:'text/csv'}},res);
  assert.equal(res.statusCode,200);assert.equal(res.value.full_report.financial.historicalRevenue.length,3);
  assert.equal(res.value.full_report.simulation.baselineGrowth,.25);
  assert.equal(res.value.full_report.simulation.summary.incrementalBaseVsStatusQuo,0);
  console.log('v3.4.1 verified: financial CSV, conflicting currencies, baseline suppression, missing evidence, plausibility withholding, scenario reconciliation, forecast API');
})().catch(e=>{console.error(e);process.exitCode=1;});
